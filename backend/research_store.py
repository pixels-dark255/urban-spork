"""Where a phase's result is kept so the dashboard can read it.

One row per phase, replaced on each run, plus an append-only history keyed
by fingerprint so an older run can still be looked up and compared.

Postgres when DATABASE_URL is set, a JSON file otherwise. Unlike the bar
archive, a file is acceptable here: a phase result can be regenerated by
re-running the phase, whereas intraday bars that were not captured are
gone for good.
"""
from __future__ import annotations

import json
import os
import threading

import jsonsafe
import storage

PATH = os.path.join(storage.DATA_DIR, "research.json")
_lock = threading.RLock()

DDL = """
CREATE TABLE IF NOT EXISTS research_results (
    phase       TEXT NOT NULL,
    fingerprint TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    data        JSONB NOT NULL,
    PRIMARY KEY (phase, fingerprint)
)
"""


def _ensure() -> None:
    conn = storage._pg_pool.getconn()
    try:
        with conn.cursor() as cur:
            cur.execute(DDL)
        conn.commit()
    finally:
        storage._pg_pool.putconn(conn)


def _file_all() -> dict:
    try:
        with open(PATH, encoding="utf-8") as fh:
            return json.load(fh)
    except (FileNotFoundError, json.JSONDecodeError):
        return {}


def save(phase: str, fingerprint: str, payload: dict) -> str:
    """Store a phase result. Returns the backend that took it."""
    clean = jsonsafe.clean(payload)
    with _lock:
        if storage._pg_pool:
            _ensure()
            conn = storage._pg_pool.getconn()
            try:
                with conn.cursor() as cur:
                    cur.execute(
                        "INSERT INTO research_results (phase, fingerprint, data) "
                        "VALUES (%s, %s, %s) "
                        "ON CONFLICT (phase, fingerprint) DO UPDATE "
                        "SET data = EXCLUDED.data, created_at = now()",
                        (phase, fingerprint, json.dumps(clean)))
                conn.commit()
            finally:
                storage._pg_pool.putconn(conn)
            return "postgres"
        everything = _file_all()
        everything.setdefault(phase, {})[fingerprint] = clean
        everything[phase]["__latest__"] = fingerprint
        os.makedirs(os.path.dirname(PATH), exist_ok=True)
        with open(PATH, "w", encoding="utf-8") as fh:
            json.dump(everything, fh)
        return "json_file"


def load(phase: str, fingerprint: str | None = None) -> dict | None:
    """The newest result for a phase, or a specific one by fingerprint."""
    with _lock:
        if storage._pg_pool:
            _ensure()
            conn = storage._pg_pool.getconn()
            try:
                with conn.cursor() as cur:
                    if fingerprint:
                        cur.execute(
                            "SELECT data FROM research_results "
                            "WHERE phase = %s AND fingerprint = %s",
                            (phase, fingerprint))
                    else:
                        cur.execute(
                            "SELECT data FROM research_results WHERE phase = %s "
                            "ORDER BY created_at DESC LIMIT 1", (phase,))
                    row = cur.fetchone()
            finally:
                storage._pg_pool.putconn(conn)
            return row[0] if row else None
        bucket = _file_all().get(phase) or {}
        key = fingerprint or bucket.get("__latest__")
        return bucket.get(key) if key else None
